def get_hero_core_items(hero_id: int) -> list[dict]:
    """
    Returns 4-5 signature core items built ON this hero with lore-accurate explanations.
    """
    from services.hero_guides import ITEM_CATALOG

    raw_items = HERO_CORE_BUILDS.get(hero_id) or get_default_role_core_items(hero_id)
    result = []
    seen = set()

    for slug, reason in raw_items:
        if slug in seen:
            continue
        seen.add(slug)
        meta = ITEM_CATALOG.get(slug)
        if not meta:
            # Fallback icon URL
            meta = {
                "slug": slug,
                "name": slug.replace("_", " ").title(),
                "name_ru": slug.replace("_", " ").title(),
                "icon_url": f"{STEAM_ITEM_CDN}/{slug}.png"
            }
        result.append({
            "slug": meta["slug"],
            "name": meta["name"],
            "name_ru": meta.get("name_ru", meta["name"]),
            "icon_url": meta["icon_url"],
            "reason": reason
        })
        if len(result) >= 5:
            break

    return result


