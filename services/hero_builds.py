def get_situational_items_for_hero_vs_enemies(hero_id: int, enemy_ids: list[int]) -> list[dict]:
    """
    Given the recommended hero_id and the picked enemy_ids, recommends 2-4 specific items
    that hero_id actually builds against THESE exact enemies, with a concrete explanation
    naming the enemy hero.
    """
    if not enemy_ids:
        return []

    from services.hero_guides import ITEM_CATALOG, HERO_MECHANICAL_TRAITS

    hero_info = HERO_BY_ID.get(hero_id, {})
    hero_role = HERO_PRIMARY_ROLE.get(hero_id, 3)
    hero_atk = hero_info.get("attack_type", "Melee")
    hero_attr = hero_info.get("primary_attr", "str")
    is_core = (hero_role in (1, 2, 3))

    RIGHT_CLICK_CORES = {
        1, 4, 6, 8, 10, 11, 12, 15, 18, 19, 21, 23, 25, 28, 32, 35, 41, 42,
        44, 46, 47, 48, 49, 53, 54, 56, 59, 61, 63, 67, 70, 72, 73, 76, 77,
        80, 81, 82, 89, 93, 94, 95, 104, 109, 113, 114, 120, 126, 136, 138, 145
    }
    TANK_OFFLANERS = {
        2, 14, 16, 19, 28, 29, 33, 38, 49, 51, 55, 60, 69, 71, 78, 83, 85,
        96, 97, 98, 99, 102, 104, 108, 129, 135, 137
    }
    HEX_BUILDERS = {
        13, 16, 17, 22, 34, 36, 39, 43, 45, 52, 53, 65, 74, 76, 86, 87, 90,
        101, 106, 107, 113, 119, 126, 139
    }

    is_right_click = (hero_id in RIGHT_CLICK_CORES) or (hero_role == 1)
    is_melee_carry = (is_right_click and hero_atk == "Melee" and hero_id not in (10, 11, 46, 72, 138))
    is_tank_offlaner = (hero_id in TANK_OFFLANERS) or (hero_role == 3 and hero_attr == "str")
    is_spell_core = (is_core and not is_right_click)
    is_hex_builder = (hero_id in HEX_BUILDERS) or (hero_attr == "int" and is_core)

    # Prevent recommending duplicate items that are already #1 in core build if better situational exists
    core_slugs = {slug for slug, _ in HERO_CORE_BUILDS.get(hero_id, [])}

    candidates: list[dict] = []
    seen_slugs = set()

    def add_cand(slug: str, e_name: str, reason: str):
        if slug not in seen_slugs:
            candidates.append({
                "slug": slug,
                "target_enemy": e_name,
                "reason": reason
            })
            seen_slugs.add(slug)

    for e_id in enemy_ids:
        e_info = HERO_BY_ID.get(e_id, {})
        e_name = e_info.get("localized_name", f"Hero #{e_id}")
        e_tags = set(HERO_MECHANICAL_TRAITS.get(e_id, []))

        # 1. Against Illusionists & Clones (PL, Naga, CK, Meepo, TB)
        if any(t in e_tags for t in ("illusionist", "clone_meepo")) or e_id in (12, 89, 81, 82, 109):
            if is_melee_carry and hero_id in (1, 8, 18, 41, 42, 44, 70, 73, 95, 114, 145):
                add_cand("bfury", e_name, f"Против {e_name}: сплэш-урон позволяет быстро зачищать пачки иллюзий и клонов.")
            elif is_right_click:
                add_cand("mjollnir", e_name, f"Против {e_name}: цепные молнии и активный щит моментально выжигают иллюзии.")
            elif is_tank_offlaner or is_spell_core:
                add_cand("shivas_guard", e_name, f"Против {e_name}: снижает скорость атаки копий на 45 и наносит АоЕ-урон волной.")
            else:
                add_cand("glimmer_cape", e_name, f"Против {e_name}: позволяет уйти в невидимость и сбросить фокус иллюзий.")

        # 2. Against True Self-Healing / Lifesteal / High-Regen Cores (Huskar, Morph, Bristle, Necro, Alch, LS, Slark, Timber)
        if "high_regen_heal" in e_tags or e_id in (59, 10, 99, 36, 73, 54, 93, 98, 14):
            if not is_core or hero_id in (17, 39, 65, 71, 88, 107, 120, 126, 136):
                add_cand("spirit_vessel", e_name, f"Против {e_name}: снижает лечение и регенерацию на 45% и выжигает процент HP.")
            elif is_right_click and hero_id in (6, 8, 10, 11, 12, 35, 41, 46, 48, 56, 63, 67, 72, 82, 89, 93, 94, 109, 113):
                add_cand("skadi", e_name, f"Против {e_name}: режет лечение, вампиризм и регенерацию на 40% при атаках.")
            else:
                add_cand("shivas_guard", e_name, f"Против {e_name}: аура заморозки режет лечение, регенерацию и вампиризм врага на 25%.")

        # 3. Against Evasion / Blur / Windrun (PA, Windranger, Brewmaster, Troll, Hoodwink)
        if "evasion" in e_tags or e_id in (44, 21, 78, 95, 123):
            if is_right_click:
                add_cand("monkey_king_bar", e_name, f"Против {e_name}: дает 80% True Strike, пробивая уклонение и промахи.")
            elif is_hex_builder:
                add_cand("sheepstick", e_name, f"Против {e_name}: мгновенный хекс отключает мобильность и позволяет сфокусировать цель.")

        # 4. Against Critical Passives (Bristleback, Spectre, Huskar, Tidehunter, Timbersaw, DK, Abaddon)
        if "passive_dependent" in e_tags or e_id in (99, 29, 67, 59, 98, 49, 102):
            if is_right_click and hero_id in (6, 8, 11, 15, 18, 19, 23, 25, 28, 35, 42, 46, 47, 49, 53, 54, 63, 70, 73, 93, 95, 104, 114, 136, 138):
                add_cand("silver_edge", e_name, f"Против {e_name}: накладывает Истощение (Break) на 5 сек., полностью отключая пассивки.")

        # 5. Against Elusive / Mobile Spellcasters (Storm, Puck, AM, QoP, Ember, Void Spirit, Weaver, Pangolier)
        if any(t in e_tags for t in ("high_mobility_spellcaster", "elusive")) or e_id in (17, 13, 1, 39, 106, 126, 63, 120):
            if is_hex_builder:
                add_cand("sheepstick", e_name, f"Против {e_name}: мгновенный хекс без каст-тайма не дает уйти в эскейп или прожать ульт.")
            elif is_right_click or hero_role == 2:
                add_cand("orchid", e_name, f"Против {e_name}: мгновенное безмолвие (Silence) на 5 сек. блокирует способности побега.")
            elif hero_atk == "Melee" and is_core:
                add_cand("abyssal_blade", e_name, f"Против {e_name}: мгновенное оглушение сквозь BKB удерживает мобильную цель на месте.")
            else:
                add_cand("gungir", e_name, f"Против {e_name}: AoE-оцепенение запрещает применять прыжки и телепорты.")

        # 6. Against Save Supports & Dispellable Buffs (Oracle, Dazzle, Omniknight, Pugna, Necrophos, Abaddon, Ringmaster, Wyvern)
        if "save_support" in e_tags or e_id in (111, 50, 57, 45, 36, 102, 79, 139, 112):
            if e_id in (57, 45, 36, 102, 21) and is_right_click:
                add_cand("nullifier", e_name, f"Против {e_name}: непрерывно развеивает защитные баффы, астрал и сейв-предметы.")
            elif is_right_click and e_id in (111, 50, 112, 139, 79):
                add_cand("nullifier", e_name, f"Против {e_name}: снимает защитные предметы (Force Staff / Ghost / Glimmer), позволяя быстро убить саппорта.")
            elif is_tank_offlaner:
                if "blink" not in core_slugs:
                    add_cand("blink", e_name, f"Против {e_name}: мгновенный прыжок в бэклайн для фокуса саппорта до нажатия сейв-ультимейта.")
                else:
                    add_cand("lotus_orb", e_name, f"Против {e_name}: сбрасывает негативные эффекты и отражает направленные скиллы саппорта.")
            elif is_hex_builder or hero_role == 2:
                add_cand("orchid", e_name, f"Против {e_name}: безмолвие не дает саппорту нажать ключевой сейв (False Promise / Grave) в драке.")

        # 7. Against Mana Shield (Medusa)
        if "mana_shield" in e_tags or e_id == 94:
            if is_right_click:
                add_cand("diffusal_blade", e_name, f"Против {e_name}: выжигает ману при каждой атаке, быстро разрушая Mana Shield.")
            elif is_tank_offlaner:
                add_cand("crimson_guard", e_name, f"Против {e_name}: блокирует физический урон от стрел Split Shot для всей команды.")

        # 8. Against Single-Target BKB-Piercing Ultimates (Legion Commander, Doom, Bane, Beastmaster, Batrider)
        if e_id in (104, 69, 3, 38, 65):
            if is_core:
                add_cand("sphere", e_name, f"Против {e_name}: блокирует направленный ультимейт сквозь BKB (Duel, Doom, Fiend's Grip, Lasso).")
            else:
                add_cand("lotus_orb", e_name, f"Против {e_name}: снимает дебаффы и отражает направленные способности обратно.")

        # 9. Against Heavy Magic Burst & AoE Control (Zeus, Skywrath, Lina, Leshrac, Invoker, Tinker, Ember, Storm, Lion, Shaman)
        if "magic_burst" in e_tags or e_id in (22, 101, 25, 52, 74, 34, 106, 17, 26, 27):
            if is_tank_offlaner:
                add_cand("pipe", e_name, f"Против {e_name}: дает всей команде магический барьер и сопротивление магии против прокаста.")
            elif not is_core:
                add_cand("glimmer_cape", e_name, f"Против {e_name}: невидимость и магический барьер спасают под магическим фокусом.")
            elif is_core and "black_king_bar" not in core_slugs:
                add_cand("black_king_bar", e_name, f"Против {e_name}: дает невосприимчивость к эффектам и защиту от магического прокаста.")
            elif is_core:
                add_cand("mage_slayer", e_name, f"Против {e_name}: снижает наносимый целью урон от всех заклинаний на 40%.")

        # 10. Against Heavy Right-Click Physical Carries (Sven, Ursa, PA, Troll, Sniper, Drow, TA, Muerta, Weaver, Clinkz, TB, Slark)
        if e_id in (18, 70, 44, 95, 35, 6, 46, 138, 63, 56, 109, 93, 54, 81):
            if not is_core:
                add_cand("ghost", e_name, f"Против {e_name}: дает 100% неуязвимость к физическим атакам на 4 секунды.")
            elif is_tank_offlaner:
                add_cand("blade_mail", e_name, f"Против {e_name}: возвращает взрывной физический урон обратно во вражеского керри.")
            elif is_spell_core:
                add_cand("shivas_guard", e_name, f"Против {e_name}: дает +15 брони и замедляет скорость атаки вражеского керри.")

        if len(candidates) >= 3:
            break

    # Format output items with metadata
    result = []
    for cand in candidates[:4]:
        meta = ITEM_CATALOG.get(cand["slug"])
        if not meta:
            meta = {
                "slug": cand["slug"],
                "name": cand["slug"].replace("_", " ").title(),
                "name_ru": cand["slug"].replace("_", " ").title(),
                "icon_url": f"{STEAM_ITEM_CDN}/{cand['slug']}.png"
            }
        result.append({
            "slug": meta["slug"],
            "name": meta["name"],
            "name_ru": meta.get("name_ru", meta["name"]),
            "icon_url": meta["icon_url"],
            "reason": cand["reason"]
        })

    return result
